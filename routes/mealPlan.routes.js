import { Router } from 'express';
import * as c from '../controllers/mealPlan.controller.js';
import { auth } from '../middlewares/auth.js';
import { validate } from '../middlewares/validate.js';
import { aiLimiter } from '../middlewares/rateLimit.js';
import { generatePlanSchema, eatenSchema, swapSchema, replaceMealSchema, fridgeSchema, addMealSchema, suggestSchema, estimateSchema } from '../validators/index.js';

const router = Router();
router.use(auth);
router.get('/current', c.getCurrent);
router.get('/history', c.history);
router.post('/generate', aiLimiter, validate(generatePlanSchema), c.generate);
router.post('/fridge', aiLimiter, validate(fridgeSchema), c.fridge);
router.post('/blank', c.createBlank);
router.post('/estimate', aiLimiter, validate(estimateSchema), c.estimate);
router.post('/:planId/days/:dayIndex/meals', validate(addMealSchema), c.addMeal);
router.post('/:planId/days/:dayIndex/suggest', aiLimiter, validate(suggestSchema), c.suggest);
router.delete('/:planId/meals/:mealId', c.removeMeal);
router.get('/:planId/meals/:mealId/recipe', aiLimiter, c.getRecipe);
router.patch('/:planId/meals/:mealId', validate(eatenSchema), c.setEaten);
router.post('/:planId/meals/:mealId/swap', aiLimiter, validate(swapSchema), c.swap);
router.put('/:planId/meals/:mealId', validate(replaceMealSchema), c.replace);
export default router;
